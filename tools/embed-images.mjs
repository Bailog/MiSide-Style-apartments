// Packs the painting images into an ES module as data URIs, so textures load
// without extra requests (also works where file:// image loading is restricted).
// Usage: node tools/embed-images.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, parse } from 'node:path';

const dir = 'assets/paintings';
const lines = ['// Generated by tools/embed-images.mjs from assets/paintings. Do not edit by hand.'];
for (const file of readdirSync(dir).sort()) {
  const { name, ext } = parse(file);
  if (!['.jpg', '.jpeg', '.png'].includes(ext.toLowerCase())) continue;
  const mime = ext.toLowerCase() === '.png' ? 'image/png' : 'image/jpeg';
  const b64 = readFileSync(join(dir, file)).toString('base64');
  lines.push(`export const ${name} = 'data:${mime};base64,${b64}';`);
}
writeFileSync('src/generated/images.js', lines.join('\n') + '\n');
console.log('wrote src/generated/images.js');
